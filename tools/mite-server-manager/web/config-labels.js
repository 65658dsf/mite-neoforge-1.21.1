function lookup(dictionary, key) {
    return dictionary && Object.prototype.hasOwnProperty.call(dictionary, key) ? dictionary[key] : undefined;
}

function pathParts(path) {
    return path.split(".").map(part => part.trim().replace(/^(["'])(.*)\1$/, "$2"));
}

function mineralLabel(key, localization) {
    const prefix = "deepslate_";
    if (key.startsWith(prefix)) {
        const base = lookup(localization.minerals, key.slice(prefix.length));
        return base && localization.deepslate + base;
    }
    return lookup(localization.minerals, key);
}

export function configLabel(kind, key, language = "zh-CN") {
    const localization = localizations[language === "en" ? "en" : "zh-CN"];
    const vocabulary = lookup(localization.labels, kind);
    if (!vocabulary || kind === "server") return lookup(vocabulary, key) ?? key;
    const parts = pathParts(key);
    const leaf = parts[parts.length - 1];
    const translation = lookup(vocabulary, parts.join(".")) ?? lookup(vocabulary, leaf);
    if (translation) return translation;
    const mineral = kind === "mite" && mineralLabel(leaf, localization);
    return mineral ? mineral + " · " + localization.oreMultiplier : key;
}

export function sectionLabel(kind, section, language = "zh-CN") {
    const localization = localizations[language === "en" ? "en" : "zh-CN"];
    if (!section) return localization.general;
    const vocabulary = lookup(localization.sections, kind);
    if (!vocabulary) return section;
    const parts = pathParts(section);
    const generation = kind === "mite" && parts[0].endsWith("_generation");
    const translated = parts.map((part, index) =>
        lookup(vocabulary, part) ?? (generation && index === 1 ? mineralLabel(part, localization) : undefined) ?? part);
    return parts.some((part, index) => part !== translated[index]) ? translated.join(" / ") : section;
}
